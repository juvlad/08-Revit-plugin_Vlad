using Autodesk.Revit.UI;
using VladTools.Commands;
using VladTools.Infrastructure;

namespace VladTools
{
    /// <summary>
    /// Точка входа надстройки: создаёт вкладку и кнопки на ленте Revit.
    /// </summary>
